#!/usr/bin/env python3
"""
xlam Dataset Verification Script

Verifies availability and accessibility of the xlam-function-calling-60k dataset
from HuggingFace Hub before training.

This project uses xlam exclusively for function calling training.

Usage:
    uv run python scripts/verify_datasets.py
"""

import sys
from pathlib import Path
from typing import Dict, List, Optional
from dataclasses import dataclass
import os
from datetime import datetime

# Add src to path
sys.path.insert(0, str(Path(__file__).parent.parent))

from datasets import load_dataset, DatasetDict, Dataset
from dotenv import load_dotenv

# Load environment variables
load_dotenv()


@dataclass
class DatasetInfo:
    """Information about the xlam dataset."""
    name: str
    hf_path: str
    requires_auth: bool
    verified: bool = False
    num_records: int = 0
    splits: List[str] = None
    error_message: str = ""
    sample_fields: List[str] = None


class XlamDatasetVerifier:
    """Verify xlam function calling dataset from HuggingFace."""

    XLAM_CONFIG = {
        "name": "xLAM Function Calling 60K (Salesforce)",
        "hf_path": "Salesforce/xlam-function-calling-60k",
        "requires_auth": True,
        "expected_format": ["query", "tools", "answers"],
        "expected_records": 60000,
        "quality_rating": "95%+ accuracy",
        "generation": "DeepSeek-V2 + Mixtral-8x22B",
    }

    def __init__(self):
        self.result: Optional[DatasetInfo] = None
        self.hf_token = os.getenv("HF_TOKEN")

    def verify(self) -> DatasetInfo:
        """Verify xlam dataset availability and accessibility."""
        print("=" * 80)
        print("🔍 XLAM DATASET VERIFICATION")
        print("=" * 80)
        print(f"📅 Timestamp: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")

        # Check HF_TOKEN
        if self.hf_token:
            print(f"🔑 HuggingFace Token: ✅ Found (length: {len(self.hf_token)})")
        else:
            print("🔑 HuggingFace Token: ❌ NOT FOUND")
            print("   ⚠️  xlam dataset requires authentication")
            print("   → Add HF_TOKEN to your .env file")
            print("   → See docs/DATASET_SETUP.md for instructions\n")

        print("=" * 80)
        print()

        # Verify xlam dataset
        self.result = self._verify_xlam()

        # Print summary
        self._print_summary()

        # Save report
        self._save_report()

        return self.result

    def _verify_xlam(self) -> DatasetInfo:
        """Verify xlam dataset from HuggingFace Hub."""
        config = self.XLAM_CONFIG

        print(f"📦 Dataset: {config['name']}")
        print(f"   🔗 HuggingFace Path: {config['hf_path']}")
        print(f"   🔒 Requires Auth: Yes (gated dataset)")
        print(f"   📊 Expected Records: ~{config['expected_records']:,}")
        print(f"   🎯 Quality: {config['quality_rating']}")
        print(f"   🤖 Generated by: {config['generation']}")
        print()

        info = DatasetInfo(
            name=config["name"],
            hf_path=config["hf_path"],
            requires_auth=config["requires_auth"],
        )

        # Check authentication
        if not self.hf_token:
            info.error_message = (
                "Authentication required but HF_TOKEN not found in .env file"
            )
            print(f"   ❌ FAILED: {info.error_message}\n")
            return info

        # Try loading dataset
        print(f"   ⏳ Loading from HuggingFace Hub...")
        try:
            dataset = load_dataset(
                config["hf_path"],
                split="train",
                token=self.hf_token
            )

            # Extract info
            info.verified = True
            info.num_records = len(dataset)
            info.sample_fields = list(dataset.features.keys())

            # Get all splits
            try:
                full_dataset = load_dataset(config["hf_path"], token=self.hf_token)
                if isinstance(full_dataset, DatasetDict):
                    info.splits = list(full_dataset.keys())
                else:
                    info.splits = ["train"]
            except Exception:
                info.splits = ["train"]

            # Verify format
            expected_fields = config["expected_format"]
            missing_fields = [f for f in expected_fields if f not in info.sample_fields]

            print(f"   ✅ SUCCESS!\n")
            print(f"   📊 Dataset Statistics:")
            print(f"      • Records: {info.num_records:,}")
            print(f"      • Splits: {', '.join(info.splits)}")
            print(f"      • Fields: {', '.join(info.sample_fields)}")

            if missing_fields:
                print(f"      ⚠️  Missing expected fields: {missing_fields}")

            # Show sample record
            if info.num_records > 0:
                sample = dataset[0]
                print(f"\n   📄 Sample Record (first example):")
                for key in list(sample.keys())[:3]:  # Show first 3 fields
                    value = str(sample[key])
                    if len(value) > 100:
                        value = value[:100] + "..."
                    print(f"      • {key}: {value}")

            print()

        except Exception as e:
            error_str = str(e)
            info.error_message = error_str

            print(f"   ❌ FAILED TO LOAD\n")
            print(f"   🛑 Error: {error_str}\n")

            # Provide helpful diagnostics
            if "gated" in error_str.lower() or "access" in error_str.lower():
                print("   💡 Diagnosis: Dataset access not granted")
                print("   → You need to accept the dataset terms on HuggingFace")
                print("   → Visit: https://huggingface.co/datasets/Salesforce/xlam-function-calling-60k")
                print("   → Click 'Agree and access repository'")
                print("   → Wait 5-10 minutes for permissions to propagate")
                print("   → Re-run this verification script\n")
            elif "token" in error_str.lower():
                print("   💡 Diagnosis: Authentication token issue")
                print("   → Check that HF_TOKEN is correctly set in .env")
                print("   → Generate new token at: https://huggingface.co/settings/tokens")
                print("   → Use 'Read' token type (not 'Write')\n")
            else:
                print("   💡 Common issues:")
                print("   → Internet connection")
                print("   → HuggingFace Hub service availability")
                print("   → Firewall/proxy settings\n")

        return info

    def _print_summary(self):
        """Print verification summary."""
        print("=" * 80)
        print("📊 VERIFICATION SUMMARY")
        print("=" * 80)

        if self.result.verified:
            print("✅ xlam dataset: VERIFIED")
            print(f"   → {self.result.num_records:,} records loaded successfully")
            print(f"   → Ground truth tool calls available for training")
            print(f"   → Ready for GRPO training with semantic reward validation\n")

            print("🚀 NEXT STEPS:")
            print("   You can now start training:")
            print("   $ uv run python scripts/train_rl.py\n")
        else:
            print("❌ xlam dataset: FAILED")
            print(f"   → Reason: {self.result.error_message}\n")

            print("🛑 CANNOT PROCEED WITH TRAINING")
            print("   This project requires xlam dataset for training.")
            print("   Please resolve the issues above and re-run verification.\n")

        print("=" * 80)

    def _save_report(self):
        """Save verification report to log file."""
        log_dir = Path("logs")
        log_dir.mkdir(exist_ok=True)

        report_file = log_dir / "dataset_verification.log"

        with open(report_file, "w") as f:
            f.write("=" * 80 + "\n")
            f.write("XLAM DATASET VERIFICATION REPORT\n")
            f.write("=" * 80 + "\n")
            f.write(f"Timestamp: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")
            f.write(f"HF_TOKEN configured: {'Yes' if self.hf_token else 'No'}\n")
            f.write("=" * 80 + "\n\n")

            f.write(f"Dataset: {self.result.name}\n")
            f.write(f"Path: {self.result.hf_path}\n")
            f.write(f"Status: {'✅ VERIFIED' if self.result.verified else '❌ FAILED'}\n")
            f.write(f"Requires Auth: Yes\n")

            if self.result.verified:
                f.write(f"Records: {self.result.num_records:,}\n")
                f.write(f"Splits: {', '.join(self.result.splits)}\n")
                f.write(f"Fields: {', '.join(self.result.sample_fields)}\n")
            else:
                f.write(f"Error: {self.result.error_message}\n")

            f.write("\n")

        print(f"📄 Verification report saved to: {report_file}")
        print()


def main():
    """Main entry point."""
    verifier = XlamDatasetVerifier()
    result = verifier.verify()

    # Exit with appropriate code
    if result.verified:
        print("✅ SUCCESS: xlam dataset verified and ready for training!")
        sys.exit(0)
    else:
        print("❌ FAILURE: xlam dataset verification failed.")
        print("   Training cannot proceed. Please fix the issues above.")
        sys.exit(1)


if __name__ == "__main__":
    main()
